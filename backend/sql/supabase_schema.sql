create table if not exists public.profiles (
  id uuid primary key,
  email text unique not null,
  name text not null,
  role text not null default 'student' check (role in ('student', 'faculty', 'admin')),
  picture text,
  clerk_user_id text unique,
  auth_provider text not null default 'supabase',
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.documents (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  description text,
  doc_type text not null default 'pdf' check (doc_type in ('pdf', 'docx', 'txt', 'csv', 'pptx', 'json', 'url')),
  filename text not null,
  storage_bucket text not null default 'documents',
  storage_path text,
  file_size bigint not null default 0,
  chunk_count integer not null default 0,
  status text not null default 'pending' check (status in ('pending', 'processing', 'indexed', 'failed')),
  uploaded_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default timezone('utc', now()),
  indexed_at timestamptz,
  error_message text,
  is_seed boolean not null default false,
  seed_origin text,
  category text,
  source_url text,
  verified_on timestamptz,
  total_parts integer not null default 1,
  processing_metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.chat_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.chat_sessions (id) on delete cascade,
  role text not null check (role in ('user', 'assistant', 'system')),
  content text not null,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.query_logs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references public.profiles (id) on delete set null,
  query text not null,
  response_length integer not null default 0,
  sources_count integer not null default 0,
  voice_input boolean not null default false,
  processing_time_ms integer not null default 0,
  is_web_fallback boolean not null default false,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.document_chunks (
  id uuid primary key default gen_random_uuid(),
  document_id uuid not null references public.documents (id) on delete cascade,
  chunk_index integer not null,
  chunk_text text not null,
  embedding vector(768),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default timezone('utc', now())
);

