create or replace function public.upsert_document_chunk(
  p_document_id uuid,
  p_chunk_index integer,
  p_chunk_text text,
  p_embedding_text text,
  p_metadata jsonb default '{}'::jsonb
)
returns uuid
language plpgsql
security definer
as $$
declare
  v_id uuid;
begin
  insert into public.document_chunks (
    document_id,
    chunk_index,
    chunk_text,
    embedding,
    metadata
  )
  values (
    p_document_id,
    p_chunk_index,
    p_chunk_text,
    p_embedding_text::vector(768),
    coalesce(p_metadata, '{}'::jsonb)
  )
  on conflict (document_id, chunk_index)
  do update set
    chunk_text = excluded.chunk_text,
    embedding = excluded.embedding,
    metadata = excluded.metadata
  returning id into v_id;

  return v_id;
end;
$$;

create or replace function public.upsert_document_chunk(payload jsonb)
returns uuid
language plpgsql
security definer
as $$
begin
  return public.upsert_document_chunk(
    (payload ->> 'p_document_id')::uuid,
    (payload ->> 'p_chunk_index')::integer,
    payload ->> 'p_chunk_text',
    payload ->> 'p_embedding_text',
    coalesce(payload -> 'p_metadata', '{}'::jsonb)
  );
end;
$$;

create or replace function public.match_document_chunks(
  query_embedding_text text,
  match_count integer default 5,
  match_document_id uuid default null
)
returns table (
  id uuid,
  document_id uuid,
  chunk_index integer,
  chunk_text text,
  metadata jsonb,
  similarity double precision
)
language sql
stable
security definer
as $$
  select
    dc.id,
    dc.document_id,
    dc.chunk_index,
    dc.chunk_text,
    dc.metadata,
    1 - (dc.embedding <=> query_embedding_text::vector(768)) as similarity
  from public.document_chunks dc
  where dc.embedding is not null
    and (match_document_id is null or dc.document_id = match_document_id)
  order by dc.embedding <=> query_embedding_text::vector(768)
  limit greatest(match_count, 1);
$$;

create or replace function public.match_document_chunks(payload jsonb)
returns table (
  id uuid,
  document_id uuid,
  chunk_index integer,
  chunk_text text,
  metadata jsonb,
  similarity double precision
)
language sql
stable
security definer
as $$
  select *
  from public.match_document_chunks(
    payload ->> 'query_embedding_text',
    coalesce((payload ->> 'match_count')::integer, 5),
    case
      when payload ? 'match_document_id' and payload ->> 'match_document_id' <> ''
      then (payload ->> 'match_document_id')::uuid
      else null
    end
  );
$$;

create or replace function public.delete_document_chunks(
  p_document_id uuid
)
returns integer
language plpgsql
security definer
as $$
declare
  deleted_rows integer;
begin
  delete from public.document_chunks
  where document_id = p_document_id;

  get diagnostics deleted_rows = row_count;
  return deleted_rows;
end;
$$;

create or replace function public.delete_document_chunks(payload jsonb)
returns integer
language plpgsql
security definer
as $$
begin
  return public.delete_document_chunks((payload ->> 'p_document_id')::uuid);
end;
$$;

