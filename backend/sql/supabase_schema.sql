drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own"
on public.profiles for select
to authenticated
using (auth.uid() = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own"
on public.profiles for update
to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

drop policy if exists "documents_select_all_authenticated" on public.documents;
create policy "documents_select_all_authenticated"
on public.documents for select
to authenticated
using (true);

drop policy if exists "chat_sessions_manage_own" on public.chat_sessions;
create policy "chat_sessions_manage_own"
on public.chat_sessions for all
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "chat_messages_manage_own" on public.chat_messages;
create policy "chat_messages_manage_own"
on public.chat_messages for all
to authenticated
using (
  exists (
    select 1
    from public.chat_sessions s
    where s.id = session_id
      and s.user_id = auth.uid()
  )
)
with check (
  exists (
    select 1
    from public.chat_sessions s
    where s.id = session_id
      and s.user_id = auth.uid()
  )
);

drop policy if exists "query_logs_manage_own" on public.query_logs;
create policy "query_logs_manage_own"
on public.query_logs for all
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

